#!/usr/bin/ruby
# frozen_string_literal: true

require "date"
require "yaml"

abort "usage: generate_protocol_configuration.rb <input.yaml> <output.swift>" unless ARGV.length == 2

input_path, output_path = ARGV
document = YAML.safe_load(File.read(input_path), permitted_classes: [Date])

def fetch_hash(parent, key, path)
  value = parent.fetch(key)
  abort "#{path}.#{key} must be an object" unless value.is_a?(Hash)
  value
rescue KeyError
  abort "missing #{path}.#{key}"
end

def fetch_number(parent, key, path)
  value = parent.fetch(key)
  abort "#{path}.#{key} must be numeric" unless value.is_a?(Numeric)
  value
rescue KeyError
  abort "missing #{path}.#{key}"
end

def fetch_boolean(parent, key, path)
  value = parent.fetch(key)
  abort "#{path}.#{key} must be boolean" unless value == true || value == false
  value
rescue KeyError
  abort "missing #{path}.#{key}"
end

def fetch_number_array(parent, key, path)
  value = parent.fetch(key)
  valid = value.is_a?(Array) && value.all? { |item| item.is_a?(Numeric) }
  abort "#{path}.#{key} must be a numeric array" unless valid
  value
rescue KeyError
  abort "missing #{path}.#{key}"
end

def swift_boolean(value)
  value ? "true" : "false"
end

profiles = fetch_hash(document, "profiles", "root")
activity = fetch_hash(document, "activity_estimator", "root")
delivery = fetch_hash(document, "opportunity_delivery", "root")
profile_cases = [
  ["gentle", "gentle"],
  ["balanced", "balanced"],
  ["frequent_movement", "frequentMovement"],
  ["research_informed_high_frequency", "researchInformedHighFrequency"],
]

profile_bodies = profile_cases.map do |yaml_name, swift_name|
  profile = fetch_hash(profiles, yaml_name, "profiles")
  visual = fetch_hash(profile, "visual", "profiles.#{yaml_name}")
  movement = fetch_hash(profile, "movement", "profiles.#{yaml_name}")
  visual_path = "profiles.#{yaml_name}.visual"
  movement_path = "profiles.#{yaml_name}.movement"

  <<~SWIFT.chomp
    case .#{swift_name}:
        return try #{swift_name}()
  SWIFT
end

profile_factories = profile_cases.map do |yaml_name, swift_name|
  profile = fetch_hash(profiles, yaml_name, "profiles")
  visual = fetch_hash(profile, "visual", "profiles.#{yaml_name}")
  movement = fetch_hash(profile, "movement", "profiles.#{yaml_name}")
  visual_path = "profiles.#{yaml_name}.visual"
  movement_path = "profiles.#{yaml_name}.movement"

  <<~SWIFT.chomp
    private static func #{swift_name}() throws -> ProtocolConfiguration {
        try ProtocolConfiguration(
            visual: OpportunitySchedule(
                softDueSeconds: #{fetch_number(visual, "soft_due_seconds", visual_path)},
                targetSeconds: #{fetch_number(visual, "target_seconds", visual_path)},
                latestPreferredSeconds: #{fetch_number(visual, "latest_preferred_seconds", visual_path)},
                durationOptionsSeconds: [#{fetch_number(visual, "duration_seconds", visual_path)}]
            ),
            movement: OpportunitySchedule(
                softDueSeconds: #{fetch_number(movement, "soft_due_seconds", movement_path)},
                targetSeconds: #{fetch_number(movement, "target_seconds", movement_path)},
                latestPreferredSeconds: #{fetch_number(movement, "latest_preferred_seconds", movement_path)},
                durationOptionsSeconds: [
                    #{fetch_number(movement, "recommended_duration_seconds", movement_path)},
                    #{fetch_number(movement, "quick_duration_seconds", movement_path)}
                ]
            ),
            activityEstimator: activityEstimator(),
            delivery: delivery()
        )
    }
  SWIFT
end

swift = <<~SWIFT
  // Generated by scripts/generate-protocol-configuration.sh.
  // Source: research/health/machine-readable/product_protocol.yaml
  // Do not edit by hand.

  import Domain

  enum ProtocolProfileLoadingError: Error {
      case customRequiresConfiguration
  }

  enum ProtocolProfiles {
      static func configuration(for profile: ProtocolProfileID) throws -> ProtocolConfiguration {
          switch profile {
#{profile_bodies.map { |body| body.lines.map { |line| "        #{line}" }.join }.join("\n")}
          case .custom:
              throw ProtocolProfileLoadingError.customRequiresConfiguration
          }
      }

#{profile_factories.map { |factory| factory.lines.map { |line| "    #{line}" }.join }.join("\n\n")}

      private static func activityEstimator() throws -> ActivityEstimatorConfiguration {
          try ActivityEstimatorConfiguration(
              recentInputWindowSeconds: #{fetch_number(activity, "recent_input_window_seconds", "activity_estimator")},
              longIdleResetSeconds: #{fetch_number(activity, "long_idle_reset_seconds", "activity_estimator")},
              wakeUnlockGraceSeconds: #{fetch_number(activity, "wake_unlock_grace_seconds", "activity_estimator")}
          )
      }

      private static func delivery() throws -> OpportunityDeliveryConfiguration {
          try OpportunityDeliveryConfiguration(
              waitForLowFrictionMoment: #{swift_boolean(fetch_boolean(delivery, "wait_for_low_friction_moment", "opportunity_delivery"))},
              mergeWindowSeconds: #{fetch_number(delivery, "merge_window_seconds", "opportunity_delivery")},
              headsUpDefault: #{swift_boolean(fetch_boolean(delivery, "heads_up_default", "opportunity_delivery"))},
              headsUpSecondsBeforeTarget: #{fetch_number(delivery, "heads_up_seconds_before_target", "opportunity_delivery")},
              snoozeOptionsSeconds: [#{fetch_number_array(delivery, "snooze_options_seconds", "opportunity_delivery").join(", ")}],
              maximumRepeatedEscalations: #{fetch_number(delivery, "max_repeated_escalations_per_opportunity", "opportunity_delivery")},
              lockoutAllowed: #{swift_boolean(fetch_boolean(delivery, "lockout_allowed", "opportunity_delivery"))}
          )
      }
  }
SWIFT

File.write(output_path, swift)
